first_name = input("Enter your first name: ")
last_name = input("Enter your last name: ")
section = input("Enter your section: ")
favorite_subject = input("Enter your favorite subject: ")

full_name = " ".join([first_name.title(), last_name.title()])
name_code = full_name.upper()
section_upper = section.upper()
favorite_subject_capitalized = favorite_subject.title()
character_count = len(full_name)

print("Formatted Output:")
print(f"Name: {full_name}")
print(f"Name Code: {name_code}")
print(f"Section: {section_upper}")
print(f"Favorite Subject: {favorite_subject_capitalized}")
print(f"Character Count: {character_count}")
